// Estado da Aplicação
let currentFilter = 'all';
let currentPlayingItem = null;
let currentActiveServerIndex = 0;
let currentZoomScale = 1.0;
let currentZoomIndex = 0;

const ZOOM_PRESETS = [
    { label: 'Normal (100%)', scale: 1.0 },
    { label: 'Ajustar (115%)', scale: 1.15 },
    { label: 'Cinema (130%)', scale: 1.30 },
    { label: 'Tela Cheia (150%)', scale: 1.50 }
];

let selectedQualityTag = '1080p';
let selectedFolderKey = 'videos';

// Inicialização
document.addEventListener('DOMContentLoaded', () => {
    renderCatalog();
    setupEventListeners();
    setupKeyboardShortcuts();
});

function renderCatalog(items = COMPREHENSIVE_CATALOG) {
    const grid = document.getElementById('mediaGrid');
    const totalCountEl = document.getElementById('totalTitlesCount');
    grid.innerHTML = '';

    const filtered = items.filter(item => {
        if (currentFilter === 'all') return true;
        if (currentFilter === '2024') return item.year === '2024';
        return item.type === currentFilter;
    });

    if (totalCountEl) {
        totalCountEl.textContent = `${filtered.length} títulos`;
    }

    if (filtered.length === 0) {
        grid.innerHTML = `
            <div style="grid-column: 1/-1; text-align: center; padding: 60px 20px; color: #8a90a4;">
                <p style="font-size: 18px; font-weight: 600;">Nenhum título encontrado</p>
                <p style="font-size: 13px; margin-top: 8px;">Tente pesquisar por outro nome ou selecione outra categoria.</p>
            </div>
        `;
        return;
    }

    filtered.forEach(item => {
        const card = document.createElement('div');
        card.className = 'media-card';
        card.innerHTML = `
            <div class="poster-wrapper">
                <img src="${item.poster}" alt="${item.title}" class="poster-img" loading="lazy" />
                <div class="rating-badge">★ ${item.rating}</div>
            </div>
            <div class="media-info">
                <div class="media-title">${item.title}</div>
                <div class="media-meta">
                    <span>${item.year}</span>
                    <span style="text-transform: capitalize; color: #e50914; font-weight: 700;">
                        ${item.type === 'movie' ? 'Filme' : (item.type === 'series' ? 'Série' : 'Anime')}
                    </span>
                </div>
            </div>
        `;

        card.addEventListener('click', () => openPlayer(item));
        grid.appendChild(card);
    });
}

function openPlayer(item) {
    currentPlayingItem = item;
    currentActiveServerIndex = 0; // Sempre começa no Servidor 1 Dublado

    const modal = document.getElementById('playerModal');
    const titleEl = document.getElementById('playerTitle');
    const metaEl = document.getElementById('playerMeta');

    titleEl.textContent = item.title;
    metaEl.textContent = `${item.year} • A2 Miguel Cinema Dublado No-Ads`;

    // Atualiza estado visual dos botões de servidor
    updateServerButtonsUI();

    // Carrega o primeiro servidor
    loadCurrentServer();

    modal.style.display = 'flex';

    // Reset zoom
    currentZoomScale = 1.0;
    currentZoomIndex = 0;
    applyZoom();

    showToast(`▶ Abrindo: ${item.title} (Servidor 1 Dublado)`);
}

function switchServer(serverNumber) {
    if (!currentPlayingItem) return;
    const index = serverNumber - 1;
    if (index >= 0 && index < currentPlayingItem.servers.length) {
        currentActiveServerIndex = index;
        updateServerButtonsUI();
        loadCurrentServer();
        showToast(`🔄 Alternado para: Servidor ${serverNumber}`);
    }
}

function updateServerButtonsUI() {
    for (let i = 1; i <= 3; i++) {
        const btn = document.getElementById(`btnServer${i}`);
        if (btn) {
            if (i - 1 === currentActiveServerIndex) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        }
    }
}

function loadCurrentServer() {
    const frame = document.getElementById('playerFrame');
    if (!currentPlayingItem || !currentPlayingItem.servers) return;

    const url = currentPlayingItem.servers[currentActiveServerIndex] || currentPlayingItem.servers[0];
    frame.src = url;
}

function closePlayer() {
    const modal = document.getElementById('playerModal');
    const frame = document.getElementById('playerFrame');
    frame.src = 'about:blank';
    modal.style.display = 'none';
    currentPlayingItem = null;
}

// Controle de Zoom
function cycleZoom() {
    currentZoomIndex = (currentZoomIndex + 1) % ZOOM_PRESETS.length;
    currentZoomScale = ZOOM_PRESETS[currentZoomIndex].scale;
    applyZoom();
    showToast(`🔍 Zoom: ${ZOOM_PRESETS[currentZoomIndex].label}`);
}

function applyZoom() {
    const wrapper = document.getElementById('videoFrameWrapper');
    if (wrapper) {
        wrapper.style.transform = `scale(${currentZoomScale})`;
    }
}

// Janela Dedicada de Download & Edição
function openDownloadWindow() {
    if (!currentPlayingItem) {
        showToast('Abra um filme ou série primeiro para baixar!');
        return;
    }

    const overlay = document.getElementById('downloadOverlay');
    const inputName = document.getElementById('inputDownloadName');

    const cleanTitle = currentPlayingItem.title.replace(/[\/\\:*?"<>|]/g, '_').trim();
    inputName.value = `A2_${cleanTitle}_${selectedQualityTag}.mp4`;

    overlay.style.display = 'flex';
}

function closeDownloadWindow() {
    document.getElementById('downloadOverlay').style.display = 'none';
}

function triggerDownload() {
    if (!currentPlayingItem) return;

    const inputName = document.getElementById('inputDownloadName');
    let fileName = inputName.value.trim();
    if (!fileName.endsWith('.mp4')) fileName += '.mp4';

    const currentServerUrl = currentPlayingItem.servers[currentActiveServerIndex] || currentPlayingItem.servers[0];

    // Cria e dispara download no Windows
    const dummyBlob = new Blob([
        `A2 Miguel - Stream de Vídeo\nTítulo: ${currentPlayingItem.title}\nQualidade: ${selectedQualityTag}\nPasta: Downloads\\A2-Miguel-PC\\${selectedFolderKey}\nLink do Servidor: ${currentServerUrl}\n`
    ], { type: 'video/mp4' });

    const downloadUrl = URL.createObjectURL(dummyBlob);
    const a = document.createElement('a');
    a.href = currentServerUrl || downloadUrl;
    a.download = fileName;
    a.target = '_blank';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);

    closeDownloadWindow();
    showToast(`⬇️ Download iniciado: ${fileName}`);
}

function showToast(message) {
    const existing = document.querySelector('.toast-osd');
    if (existing) existing.remove();

    const toast = document.createElement('div');
    toast.className = 'toast-osd';
    toast.innerHTML = `<span>🎬</span> <span>${message}</span>`;
    document.body.appendChild(toast);

    setTimeout(() => {
        toast.style.opacity = '0';
        toast.style.transition = 'opacity 0.3s ease';
        setTimeout(() => toast.remove(), 300);
    }, 2500);
}

// Configuração de Eventos
function setupEventListeners() {
    // Busca em tempo real
    const searchInput = document.getElementById('searchInput');
    searchInput.addEventListener('input', (e) => {
        const query = e.target.value.toLowerCase().trim();
        if (!query) {
            renderCatalog(COMPREHENSIVE_CATALOG);
            return;
        }

        const filtered = COMPREHENSIVE_CATALOG.filter(item =>
            item.title.toLowerCase().includes(query) ||
            item.desc.toLowerCase().includes(query) ||
            item.year.includes(query)
        );
        renderCatalog(filtered);
    });

    // Categorias
    document.querySelectorAll('.chip').forEach(chip => {
        chip.addEventListener('click', () => {
            document.querySelectorAll('.chip').forEach(c => c.classList.remove('active'));
            chip.classList.add('active');
            currentFilter = chip.getAttribute('data-type');
            renderCatalog(COMPREHENSIVE_CATALOG);
        });
    });

    // Seletores de Servidor
    document.getElementById('btnServer1').addEventListener('click', () => switchServer(1));
    document.getElementById('btnServer2').addEventListener('click', () => switchServer(2));
    document.getElementById('btnServer3').addEventListener('click', () => switchServer(3));

    // Qualidade no modal de download
    document.querySelectorAll('.quality-box').forEach(box => {
        box.addEventListener('click', () => {
            document.querySelectorAll('.quality-box').forEach(b => b.classList.remove('selected'));
            box.classList.add('selected');
            selectedQualityTag = box.getAttribute('data-quality');

            if (currentPlayingItem) {
                const cleanTitle = currentPlayingItem.title.replace(/[\/\\:*?"<>|]/g, '_').trim();
                document.getElementById('inputDownloadName').value = `A2_${cleanTitle}_${selectedQualityTag}.mp4`;
            }
        });
    });

    // Pasta no modal de download
    document.querySelectorAll('.folder-box').forEach(box => {
        box.addEventListener('click', () => {
            document.querySelectorAll('.folder-box').forEach(b => b.classList.remove('selected-blue'));
            box.classList.add('selected-blue');
            selectedFolderKey = box.getAttribute('data-folder');
        });
    });

    // Botões do Player
    document.getElementById('btnClosePlayer').addEventListener('click', closePlayer);
    document.getElementById('btnPlayerZoom').addEventListener('click', cycleZoom);
    document.getElementById('btnPlayerDownload').addEventListener('click', openDownloadWindow);

    // Botões do Modal de Download
    document.getElementById('btnCloseDownload').addEventListener('click', closeDownloadWindow);
    document.getElementById('btnStartDownloadAction').addEventListener('click', triggerDownload);
    document.getElementById('btnCancelDownloadAction').addEventListener('click', closeDownloadWindow);
}

// Atalhos de teclado no PC
function setupKeyboardShortcuts() {
    window.addEventListener('keydown', (e) => {
        // Tecla D: Janela de Download
        if (e.key === 'd' || e.key === 'D') {
            if (currentPlayingItem && document.getElementById('downloadOverlay').style.display !== 'flex') {
                openDownloadWindow();
            }
        }
        // Tecla Z: Cicla Zoom
        if (e.key === 'z' || e.key === 'Z') {
            if (currentPlayingItem) {
                cycleZoom();
            }
        }
        // Teclas 1, 2, 3: Alterna servidores
        if (currentPlayingItem && (e.key === '1' || e.key === '2' || e.key === '3')) {
            switchServer(parseInt(e.key, 10));
        }
        // Tecla Escape: Fecha janela ou player
        if (e.key === 'Escape') {
            if (document.getElementById('downloadOverlay').style.display === 'flex') {
                closeDownloadWindow();
            } else if (currentPlayingItem) {
                closePlayer();
            }
        }
    });
}
